github_storage = "https://raw.githubusercontent.com/FacultadInformatica-LinkedData/Curso2021-2022/master/Assignment4/course_materials"

from rdflib import Graph, Namespace, Literal, URIRef
g1 = Graph()
g2 = Graph()
g1.parse(github_storage+"/rdf/data01.rdf", format="xml")
g2.parse(github_storage+"/rdf/data02.rdf", format="xml")

"""Spanish: Lista todos los elementos de la clase Person en el primer grafo (data01.rdf) y completa los campos (given name, family name y email) que puedan faltar con los datos del segundo grafo (data02.rdf). Puedes usar consultas SPARQL o iterar el grafo, o ambas cosas.

English: List all the elements of the Person class in the first graph (data01.rdf) and fill in any missing fields (given name, family name and email) using the data from the second graph (data02.rdf). You can use SPARQL queries or iterate through the graph, or both.
"""

g1.serialize(destination='data01.rdf', format='xml')
g2.serialize(destination='data02.rdf', format='xml')

print(g1.serialize(format='ttl'))
print(g2.serialize(format='ttl'))

from rdflib import RDF, Namespace
from rdflib.namespace import RDF

# Define namespaces
NS = Namespace("http://data.org#")
VCARD = Namespace("http://www.w3.org/2001/vcard-rdf/3.0#")

# Properties we want to check and complete
properties = [VCARD.Given, VCARD.Family, VCARD.EMAIL]

print("Completing missing fields in g1 using g2")

for person, _, _ in g1.triples((None, RDF.type, NS.Person)):
    print(f"\nPerson: {person}")

    for prop in properties:
        has_value_g1 = list(g1.objects(person, prop))

        if not has_value_g1:
            for value_g2 in g2.objects(person, prop):
                g1.add((person, prop, value_g2))
                print(f"  Added missing field: {prop.split('#')[-1] or prop.split('/')[-1]} -> {value_g2}")
        else:
            print(f"  Already had: {prop.split('#')[-1] or prop.split('/')[-1]} -> {has_value_g1[0]}")

print("\nUpdated triples for Person instances in g1 ===")
for s, p, o in g1.triples((None, RDF.type, NS.Person)):
    for s2, p2, o2 in g1.triples((s, None, None)):
        print(s2, p2, o2)