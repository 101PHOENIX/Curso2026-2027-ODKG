from rdflib import Graph, Namespace, Literal, URIRef
g1 = Graph()
g2 = Graph()
g3 = Graph()
g1.parse(github_storage+"rdf/data03.rdf", format="xml")
g2.parse(github_storage+"rdf/data04.rdf", format="xml")

"""Spanish: Busca individuos en los dos grafos y enlázalos mediante la propiedad OWL:sameAs, inserta estas coincidencias en g3. Consideramos dos individuos iguales si tienen el mismo apodo y nombre de familia. Ten en cuenta que las URI no tienen por qué ser iguales para un mismo individuo en los dos grafos.

English: Search for individuals in both graphs and link them using the OWL:sameAs property; insert these matches into g3. We consider two individuals to be the same if they have the same first name and surname. Please note that the URIs do not necessarily have to be the same for the same individual in both graphs.
"""

for s,p,o in g1.triples((None, None, None)):
  print(s,p,o)

print("-------------")

for s,p,o in g2.triples((None, None, None)):
  print(s,p,o)

from rdflib.namespace import OWL

vcard = Namespace("http://www.w3.org/2001/vcard-rdf/3.0#")

for personag1 in g1.subjects(vcard.Given, None, unique = True):

  #Guardo el nombre de cada persona de g1

  nombreg1 = g1.value(personag1, vcard.Given, None)

  #Guardo el apellido de cada persona de g1

  apellidog1 = g1.value(personag1, vcard.Family, None)

  for personag2 in g2.subjects(vcard.Given, None, unique = True):

    #Guardo el nombre de cada persona de g2
    nombreg2 = g2.value(personag2, vcard.Given, None)

    #Guardo el apellido de cada persona de g2
    apellidog2 = g2.value(personag2, vcard.Family, None)

    if (nombreg1 is not None and apellidog1 is not None and
    nombreg2 is not None and apellidog2 is not None and
    nombreg1 == nombreg2 and apellidog1 == apellidog2):

        g3.add((personag1, OWL.sameAs, personag2))

for s, p, o in g3:
    print(s, "sameAs", o)