#Listamos todos los elementos de la clase person del grafo g1
from rdflib.namespace import RDF
ns = Namespace("http://data.org#")

persons = list(g1.subjects(RDF.type, ns.Person))

for person in persons:
  print(person)

#Para cada propiedad de g2 que no esté en g1, lo añado
vcard = Namespace("http://www.w3.org/2001/vcard-rdf/3.0#")

propiedades = [vcard.Given, vcard.Family, vcard.EMAIL]

for person in persons:
  for propiedad in propiedades:
    for s,p,o in g2.triples((person, propiedad, None)):
      if (person,p,None) not in g1:
        print("Falta", person, propiedad)
        g1.add((person,p,o))

for person in persons:
  print(person, g1.value(person, vcard.Given), g1.value(person, vcard.Family), g1.value(person, vcard.EMAIL))